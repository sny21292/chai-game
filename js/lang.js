'use strict';
// Languages. The game is written in Hinglish (the source strings everywhere); English is the default
// language (portals require it), so every player-facing string goes through T() at draw time.
//   T('ab tak ☠ {n}', { n: 3 })  ->  'deaths so far ☠ 3' in English, the Hinglish original otherwise.
// Missing entries fall back to the Hinglish source; tools/tests/i18n.js checks that every sign, message,
// tagline and UI string has an English entry. Level names in NAME_EN; proper names are left out on purpose.
//
// Language choice: save.lang ('en' | 'hi') from Settings, else the portal's locale (hi-* gets Hinglish),
// else English.

const LANGS = { en: 'English', hi: 'Hinglish' };
let autoLang = 'en';
function setAutoLang(locale) { autoLang = /^hi\b/i.test(locale || '') ? 'hi' : 'en'; }
const lang = () => (typeof save !== 'undefined' && save.lang) || autoLang;

function T(s, vars) {
  let out = lang() === 'en' ? (EN[s] ?? NAME_EN[s] ?? s) : s;
  if (vars) out = out.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  return out;
}

